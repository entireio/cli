package opencode

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path"
	"strings"

	"github.com/entireio/cli/cmd/entire/cli/agent"
	"github.com/entireio/cli/cmd/entire/cli/logging"
	"github.com/entireio/cli/cmd/entire/cli/paths"
)

// Compile-time interface assertions
var (
	_ agent.HookSupport       = (*OpenCodeAgent)(nil)
	_ agent.HookConfigLocator = (*OpenCodeAgent)(nil)
	_ agent.HookFreshness     = (*OpenCodeAgent)(nil)
)

const (
	// pluginFileName is the name of the plugin file written to .opencode/plugin/
	pluginFileName = "entire.ts"

	// pluginDirName is the directory under .opencode/ where the plugin lives.
	// Every OpenCode loads .opencode/plugin; OpenCode 0.15 and 1.0.0 refuse to
	// start at all when .opencode/plugins exists, so it is the singular form.
	pluginDirName = "plugin"

	// legacyPluginDirName is where earlier CLIs wrote the plugin. Installing
	// moves an Entire plugin out of it: OpenCode 1.0.224+ and 2.x load both
	// directories, so leaving it would run the plugin twice.
	legacyPluginDirName = "plugins"

	// entireMarker is a string present in the plugin file to identify it as Entire's
	entireMarker = "Auto-generated by `entire enable --agent opencode`"
)

// pluginConfig returns .opencode/plugin/entire.ts for the current worktree,
// opened through the worktree's root so the plugin directory is created and
// written as a name inside the repository rather than through whatever a
// checked-in `.opencode` symlink points at.
func pluginConfig(ctx context.Context) (*agent.HookConfigFile, error) {
	return openPluginConfig(ctx, (&OpenCodeAgent{}).HookConfigRelPath())
}

// legacyPluginConfig returns .opencode/plugins/entire.ts, where earlier CLIs
// wrote the plugin.
func legacyPluginConfig(ctx context.Context) (*agent.HookConfigFile, error) {
	return openPluginConfig(ctx, ".opencode/"+legacyPluginDirName+"/"+pluginFileName)
}

func openPluginConfig(ctx context.Context, rel string) (*agent.HookConfigFile, error) {
	repoRoot, err := paths.WorktreeRoot(ctx)
	if err != nil {
		// Fallback to CWD if not in a git repo (e.g., during tests)
		//nolint:forbidigo // Intentional fallback when WorktreeRoot() fails (tests run outside git repos)
		repoRoot, err = os.Getwd()
		if err != nil {
			return nil, fmt.Errorf("failed to get current directory: %w", err)
		}
	}
	return agent.OpenHookConfig(repoRoot, rel) //nolint:wrapcheck // agent.HookConfigFile already names the file in its error
}

// legacyPluginIsOurs reports whether the legacy path holds an Entire plugin.
func legacyPluginIsOurs(ctx context.Context) (*agent.HookConfigFile, bool) {
	legacy, err := legacyPluginConfig(ctx)
	if err != nil {
		return nil, false
	}
	data, err := legacy.Read()
	if err != nil {
		return nil, false
	}
	return legacy, strings.Contains(string(data), entireMarker)
}

// removeLegacyPlugin removes an Entire plugin from the legacy directory, and
// the directory too when that leaves it empty: OpenCode 0.15 and 1.0.0
// refuse to start while it exists. A directory holding the user's own
// plugins, or a symlink, is left alone. Reports whether it removed the file.
func removeLegacyPlugin(ctx context.Context) (bool, error) {
	legacy, ours := legacyPluginIsOurs(ctx)
	if !ours {
		return false, nil
	}
	if err := legacy.Remove(); err != nil {
		return false, err //nolint:wrapcheck // agent.HookConfigFile already names the file in its error
	}
	root, name := legacy.Root()
	dir := path.Dir(name)
	if info, err := root.Lstat(dir); err == nil && info.IsDir() {
		_ = root.Remove(dir) //nolint:errcheck // fails while the user's own plugins remain, which is the point
	}
	return true, nil
}

// renderPlugin returns the plugin file content. The template names the "entire"
// binary directly — there is nothing to substitute, and deliberately so: a plugin
// that shelled out to a path inside the working tree would run whatever the
// checked-out branch contains.
func renderPlugin() string {
	return pluginTemplate
}

// InstallHooks writes the Entire plugin file to .opencode/plugin/entire.ts,
// moving it from .opencode/plugins if an earlier CLI wrote it there.
// Returns 1 if anything changed, 0 if already up-to-date (idempotent).
// If the file exists but content differs (e.g., an older render), it is rewritten.
func (a *OpenCodeAgent) InstallHooks(ctx context.Context, force bool) (int, error) {
	cfg, err := pluginConfig(ctx)
	if err != nil {
		return 0, err
	}

	content := renderPlugin()
	changed := 0

	// Check if already installed with identical content (idempotent) unless force
	upToDate := false
	if !force {
		if existing, readErr := cfg.Read(); readErr == nil && string(existing) == content {
			upToDate = true
		}
	}
	if !upToDate {
		// Write creates .opencode/plugin with MkdirAllNoSymlink. 0644 because
		// OpenCode reads the plugin itself.
		if err := cfg.Write([]byte(content), 0o644); err != nil {
			return 0, err //nolint:wrapcheck // agent.HookConfigFile already names the file in its error
		}
		changed = 1
	}

	removed, err := removeLegacyPlugin(ctx)
	if err != nil {
		return changed, err
	}
	if removed {
		changed = 1
	}
	return changed, nil
}

// UninstallHooks removes the Entire plugin file, from the legacy directory too.
func (a *OpenCodeAgent) UninstallHooks(ctx context.Context) error {
	cfg, err := pluginConfig(ctx)
	if err != nil {
		return err
	}
	if err := cfg.Remove(); err != nil {
		return err //nolint:wrapcheck // agent.HookConfigFile already names the file in its error
	}
	_, err = removeLegacyPlugin(ctx)
	return err
}

// AreHooksInstalled checks if the Entire plugin file exists and contains the marker.
//
// A missing config file is an answer, not a failure: that file is where the
// state lives, so its absence means no hooks. Anything that stops us reading the
// answer — an unreadable file, malformed config — is returned as an error, since
// "we could not tell" and "there are none" are different things to a caller
// deciding whether hooks can be left alone.
func (a *OpenCodeAgent) AreHooksInstalled(ctx context.Context) (bool, error) {
	cfg, err := pluginConfig(ctx)
	if err != nil {
		logging.Warn(ctx, "opencode: failed to resolve plugin path", "err", err)
		return false, err
	}

	data, err := cfg.Read()
	if errors.Is(err, os.ErrNotExist) {
		// Installed by an earlier CLI: it still runs on every OpenCode that
		// reads .opencode/plugins.
		_, ours := legacyPluginIsOurs(ctx)
		return ours, nil
	}
	if err != nil {
		logging.Warn(ctx, "opencode: failed to read plugin file", "path", cfg.Path(), "err", err)
		return false, fmt.Errorf("read %s: %w", cfg.Path(), err)
	}

	return strings.Contains(string(data), entireMarker), nil
}

// CheckHookConfig reports whether the installed plugin matches what
// InstallHooks would write today. Read-only diagnostic for `entire status` and
// `entire doctor`; same committed-and-stale exposure as Pi's extension, since
// .opencode/plugin/entire.ts is likewise a generated file repos commit so
// every clone is covered.
func (a *OpenCodeAgent) CheckHookConfig(ctx context.Context) agent.HookConfigState {
	cfg, err := pluginConfig(ctx)
	if err != nil {
		return agent.HooksAbsent
	}
	// A plugin an earlier CLI left in .opencode/plugins is outdated wherever
	// it is: next to a current one it makes OpenCode run the plugin twice.
	if _, ours := legacyPluginIsOurs(ctx); ours {
		return agent.HooksOutdated
	}
	// Only the binary render counts as current. A plugin left behind by
	// local-dev mode still carries entireMarker, so it reads as ours but
	// outdated and gets rewritten rather than being trusted as up to date.
	return cfg.GeneratedState(entireMarker, renderPlugin())
}

// HookConfigRelPath implements agent.HookConfigLocator.
func (a *OpenCodeAgent) HookConfigRelPath() string {
	return ".opencode/" + pluginDirName + "/" + pluginFileName
}
