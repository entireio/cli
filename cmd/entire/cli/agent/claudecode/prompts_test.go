// realTranscriptFixture is a real Claude Code session transcript shared with
// the compactor tests: string prompts, tool_result user entries, assistant
// turns, and "[Request interrupted by user]" markers.
const realTranscriptFixture = "../../transcript/compact/testdata/claude_full2.jsonl"

func TestExtractPromptsFromTranscript_RealTranscript(t *testing.T) {
	t.Parallel()
	data, err := os.ReadFile(realTranscriptFixture)
	require.NoError(t, err)

	tests := []struct {
		name   string
		offset int
		want   []string
	}{
		{
			name:   "whole transcript",
			offset: 0,
			want: []string{
				"can you take a look at the attribution logic, can you explain me again why we don't track deleted lines",
				"can you take a look at the attribution logic, can you explain me again why we don't track deleted lines",
				"can you look at b91ac0681ff15f2a9e583aa2e5b3958443ca984d and the corresponding checkpoint and logs in ../entire.io how the percentage / and lines came to be",
				"are you stuck?",
				"are you stuck?",
				"are you stuck?",
				"but why would there then be so many human_added lines",
				"what could be a fix here? Or a plan for better investigation?",
				"Let's write a test replicating what we think caused the issue in the checkpoint, then we can work on getting it fixed",
				"yeah, let's give it a try",
			},
		},
		{
			// Lines 0..199 are skipped; the prompt on line index 204 is the
			// first one after the offset.
			name:   "after a checkpoint offset",
			offset: 200,
			want: []string{
				"are you stuck?",
				"but why would there then be so many human_added lines",
				"what could be a fix here? Or a plan for better investigation?",
				"Let's write a test replicating what we think caused the issue in the checkpoint, then we can work on getting it fixed",
				"yeah, let's give it a try",
			},
		},
		{
			name:   "offset past the end",
			offset: 10_000,
			want:   nil,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			got, err := (&ClaudeCodeAgent{}).ExtractPromptsFromTranscript(data, tt.offset)
			require.NoError(t, err)
			assert.Equal(t, tt.want, got)
		})
	}
}

// The user entries Claude Code writes itself, in the shapes it writes them:
// isMeta expansions and caveats, the compaction summary, slash-command
// invocation tags, background-task notifications, interruption markers, and
// tool results.
func TestExtractPromptsFromTranscript_DropsInjectedUserEntries(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		line string
		want []string
	}{
		{
			name: "plain prompt",
			line: `{"type":"user","message":{"role":"user","content":"fix the failing test"},"uuid":"u1"}`,
			want: []string{"fix the failing test"},
		},
		{
			name: "text block prompt with an IDE tag stripped",
			line: `{"type":"user","message":{"role":"user","content":[{"type":"text","text":"<ide_opened_file>The user opened a.go</ide_opened_file>"},{"type":"text","text":"explain this file"}]},"uuid":"u2"}`,
			want: []string{"explain this file"},
		},
		{
			name: "tool result",
			line: `{"type":"user","message":{"role":"user","content":[{"tool_use_id":"toolu_01","type":"tool_result","content":"ok"}]},"uuid":"u3"}`,
		},
		{
			name: "local command caveat (isMeta)",
			line: `{"type":"user","message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"},"isMeta":true,"uuid":"u4"}`,
		},
		{
			name: "slash command expansion (isMeta)",
			line: `{"type":"user","message":{"role":"user","content":[{"type":"text","text":"Base directory for this skill: /skills/simplify\n\nReview the changed code."}]},"isMeta":true,"uuid":"u5"}`,
		},
		{
			name: "system reminder (isMeta)",
			line: `{"type":"user","message":{"role":"user","content":"<system-reminder>The task tools haven't been used recently.</system-reminder>"},"isMeta":true,"uuid":"u6"}`,
		},
		{
			name: "system reminder without isMeta",
			line: `{"type":"user","message":{"role":"user","content":"<system-reminder>Do not mention this.</system-reminder>"},"uuid":"u7"}`,
		},
		{
			name: "continuation summary",
			line: `{"type":"user","message":{"role":"user","content":"This session is being continued from a previous conversation that ran out of context."},"isCompactSummary":true,"isVisibleInTranscriptOnly":true,"uuid":"u8"}`,
		},
		{
			name: "slash command invocation",
			line: `{"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>"},"uuid":"u9"}`,
		},
		{
			name: "local command output",
			line: `{"type":"user","message":{"role":"user","content":"<local-command-stdout></local-command-stdout>"},"uuid":"u10"}`,
		},
		{
			name: "background task notification",
			line: `{"type":"user","message":{"role":"user","content":"<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n</task-notification>"},"uuid":"u11"}`,
		},
		{
			name: "interruption marker",
			line: `{"type":"user","message":{"role":"user","content":[{"type":"text","text":"[Request interrupted by user for tool use]"}]},"uuid":"u12"}`,
		},
		{
			// `!` bash mode: the command the user ran in the shell.
			name: "bash-mode input",
			line: `{"type":"user","message":{"role":"user","content":"<bash-input>git status</bash-input>"},"isSidechain":false,"userType":"external","uuid":"u13"}`,
		},
		{
			// `!` bash mode: the command's output, stdout and (empty) stderr.
			name: "bash-mode stdout",
			line: `{"type":"user","message":{"role":"user","content":"<bash-stdout>On branch main\nnothing to commit</bash-stdout><bash-stderr></bash-stderr>"},"isSidechain":false,"userType":"external","uuid":"u14"}`,
		},
		{
			name: "bash-mode stderr only",
			line: `{"type":"user","message":{"role":"user","content":"<bash-stderr>cat: missing.txt: No such file or directory</bash-stderr>"},"isSidechain":false,"userType":"external","uuid":"u15"}`,
		},
		{
			// A subagent's sidechain: the parent agent's instruction, not the user's.
			name: "sidechain user turn",
			line: `{"type":"user","message":{"role":"user","content":"Find every caller of resolveFilesTouched."},"isSidechain":true,"agentId":"a1b2c3","userType":"external","uuid":"u16"}`,
		},
		{
			name: "prompt mentioning a bash tag mid-text",
			line: `{"type":"user","message":{"role":"user","content":"why does <bash-input> show up in my prompts?"},"uuid":"u17"}`,
			want: []string{"why does <bash-input> show up in my prompts?"},
		},
		{
			name: "assistant entry",
			line: `{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"done"}]},"uuid":"a1"}`,
		},
		{
			name: "malformed line",
			line: `{"type":"user","message":`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			got, err := (&ClaudeCodeAgent{}).ExtractPromptsFromTranscript([]byte(tt.line+"\n"), 0)
			require.NoError(t, err)
			assert.Equal(t, tt.want, got)
		})
	}
}

// The offset counts lines the way GetTranscriptPosition does — blank lines and
// a final unterminated line included — so a turn-start position skips exactly
// the lines already in an earlier checkpoint.
func TestExtractPromptsFromTranscript_OffsetMatchesTranscriptPosition(t *testing.T) {
	t.Parallel()
	first := `{"type":"user","message":{"role":"user","content":"first"},"uuid":"u1"}`
	second := `{"type":"user","message":{"role":"user","content":"second"},"uuid":"u2"}`
	before := first + "\n\n"
	path := filepath.Join(t.TempDir(), "transcript.jsonl")
	require.NoError(t, os.WriteFile(path, []byte(before), 0o600))

	ag := &ClaudeCodeAgent{}
	pos, err := ag.GetTranscriptPosition(path)
	require.NoError(t, err)
	require.Equal(t, 2, pos)

	content := before + second // final line has no trailing newline
	got, err := ag.ExtractPromptsFromTranscript([]byte(content), pos)
	require.NoError(t, err)
	assert.Equal(t, []string{"second"}, got)
}

func TestExtractPrompts_ReadsPathAndToleratesMissingFile(t *testing.T) {
	t.Parallel()
	ag := &ClaudeCodeAgent{}

	path := filepath.Join(t.TempDir(), "transcript.jsonl")
	lines := []string{
		`{"type":"user","message":{"role":"user","content":"first"},"uuid":"u1"}`,
		`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"ok"}]},"uuid":"a1"}`,
		`{"type":"user","message":{"role":"user","content":"second"},"uuid":"u2"}`,
	}
	require.NoError(t, os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o600))

	got, err := ag.ExtractPrompts(path, 1)
	require.NoError(t, err)
	assert.Equal(t, []string{"second"}, got)

	got, err = ag.ExtractPrompts(filepath.Join(t.TempDir(), "missing.jsonl"), 0)
	require.NoError(t, err)
	assert.Nil(t, got)
}
