// pre-commit install after Entire's: pre-commit moved Entire's hook to .legacy.
// Entire takes the hook path back, and pre-commit's wrapper runs the user's
// hook from .legacy.
func TestInstallHooks_ReclaimsFromPreCommit(t *testing.T) {
	t.Parallel()
	spec := specFor(t, "commit-msg")
	chained := generateChainedContent(spec.content, spec.name)
	wrapper := preCommitWrapper("commit-msg")

	t.Run("with a user hook", func(t *testing.T) {
		t.Parallel()
		f := newHooksFixture(t)
		f.write("commit-msg", wrapper)
		f.write("commit-msg"+legacySuffix, chained)
		f.write("commit-msg"+backupSuffix, userHookV1)

		f.install(spec)

		assertHooks(t, f, map[string]string{
			"commit-msg":                chained,
			"commit-msg" + backupSuffix: wrapper,
			"commit-msg" + legacySuffix: userHookV1,
			"commit-msg" + keepSuffix:   userHookV1,
		})
	})

	t.Run("pre-commit was there first", func(t *testing.T) {
		t.Parallel()
		f := newHooksFixture(t)
		f.write("commit-msg", wrapper)
		f.write("commit-msg"+legacySuffix, chained)
		f.write("commit-msg"+backupSuffix, wrapper)

		f.install(spec)

		assertHooks(t, f, map[string]string{"commit-msg": chained, "commit-msg" + backupSuffix: wrapper})
		if f.exists("commit-msg" + legacySuffix) {
			t.Error(".legacy still present; pre-commit would run Entire's hook again")
		}
	})

	t.Run("pre-commit installed again", func(t *testing.T) {
		t.Parallel()
		f := newHooksFixture(t)
		f.write("commit-msg", wrapper)
		f.write("commit-msg"+legacySuffix, chained)
		f.write("commit-msg"+backupSuffix, userHookV1)
		f.install(spec)
		// pre-commit install: moves the hook it does not own onto .legacy.
		if err := os.Rename(filepath.Join(f.dir, "commit-msg"), filepath.Join(f.dir, "commit-msg"+legacySuffix)); err != nil {
			t.Fatal(err)
		}
		f.write("commit-msg", wrapper)

		f.install(spec)

		assertHooks(t, f, map[string]string{
			"commit-msg":                chained,
			"commit-msg" + backupSuffix: wrapper,
			"commit-msg" + legacySuffix: userHookV1,
		})
	})
}

func assertHooks(t *testing.T, f *hooksFixture, want map[string]string) {
	t.Helper()
	for name, content := range want {
		if !f.exists(name) {
			t.Errorf("%s missing", name)
			continue
		}
		if got := f.read(name); got != content {
			t.Errorf("%s = %q, want %q", name, got, content)
		}
	}
}

