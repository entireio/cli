// preCommitWrapper is pre-commit 4.6.2's resources/hook-tmpl, as installed.
// hookRunTimeout bounds a hook chain run by these tests. It only has to stop a
// recursive chain that never ends; the stub hooks fork a few processes, which
// can take well over 10s under -race and parallel load.
const hookRunTimeout = 60 * time.Second

func preCommitWrapper(hook string) string {
	return `#!/usr/bin/env bash
# File generated by pre-commit: https://pre-commit.com
# ID: 138fd403232d2ddd5efb44317e38bf03

# start templated
INSTALL_PYTHON=''
ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=` + hook + `)
# end templated

HERE="$(cd "$(dirname "$0")" && pwd)"
ARGS+=(--hook-dir "$HERE" -- "$@")
exec pre-commit "${ARGS[@]}"
`
}

// preCommitPythonWrapper is pre-commit 2.x's Python resources/hook-tmpl, as
// installed (INSTALL_PYTHON left empty so it runs pre-commit from PATH).
func preCommitPythonWrapper(hook string) string {
	return `#!/usr/bin/env python3
# File generated by pre-commit: https://pre-commit.com
# ID: 138fd403232d2ddd5efb44317e38bf03
import os
import sys
from shutil import which

# start templated
INSTALL_PYTHON = ''
ARGS = ['hook-impl', '--config=.pre-commit-config.yaml', '--hook-type=` + hook + `']
# end templated
ARGS.extend(('--hook-dir', os.path.realpath(os.path.dirname(__file__))))
ARGS.append('--')
ARGS.extend(sys.argv[1:])

if not which('pre-commit'):
    raise SystemExit('` + "`pre-commit`" + ` not found.')
os.execvp('pre-commit', ['pre-commit'] + ARGS)
`
}

// hooksFixture is a hooks dir and a separate lock dir, both opened as roots.
type hooksFixture struct {
	t        *testing.T
	dir      string
	root     *os.Root
	lockRoot *os.Root
}

func newHooksFixture(t *testing.T) *hooksFixture {
	t.Helper()
	dir := t.TempDir()
	root, err := os.OpenRoot(dir)
	if err != nil {
		t.Fatal(err)
	}
	lockRoot, err := os.OpenRoot(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { root.Close(); lockRoot.Close() })
	return &hooksFixture{t: t, dir: dir, root: root, lockRoot: lockRoot}
}

func (f *hooksFixture) write(name, content string) {
	f.t.Helper()
	writeExec(f.t, filepath.Join(f.dir, name), content)
}

func (f *hooksFixture) read(name string) string {
	f.t.Helper()
	data, err := os.ReadFile(filepath.Join(f.dir, name))
	if err != nil {
		f.t.Fatalf("read %s: %v", name, err)
	}
	return string(data)
}

func (f *hooksFixture) exists(name string) bool {
	_, err := os.Lstat(filepath.Join(f.dir, name))
	return err == nil
}

func (f *hooksFixture) chmod(name string, mode os.FileMode) {
	f.t.Helper()
	if err := os.Chmod(filepath.Join(f.dir, name), mode); err != nil {
		f.t.Fatal(err)
	}
}

func (f *hooksFixture) install(specs ...hookSpec) {
	f.t.Helper()
	if _, err := installHooks(context.Background(), f.lockRoot, f.root, f.dir, specs, backupClock); err != nil {
		f.t.Fatalf("installHooks: %v", err)
	}
}

// installExecutable protects the installer's writes as well as fixture writes
// when a test will execute the resulting hooks. No subprocess runs during install.
func (f *hooksFixture) installExecutable(specs ...hookSpec) {
	f.t.Helper()
	syscall.ForkLock.RLock()
	defer syscall.ForkLock.RUnlock()
	f.install(specs...)
}

func (f *hooksFixture) olderCopies() []string {
	f.t.Helper()
	copies, err := olderHookCopies(f.root)
	if err != nil {
		f.t.Fatal(err)
	}
	return copies
}

// contents returns what each name holds, for comparing sets of versions.
func (f *hooksFixture) contents(names ...string) []string {
	f.t.Helper()
	out := make([]string, 0, len(names))
	for _, n := range names {
		out = append(out, f.read(n))
	}
	slices.Sort(out)
	return out
}

func specFor(t *testing.T, name string) hookSpec {
	t.Helper()
	for _, spec := range buildHookSpecs(bareEntireHookCmd) {
		if spec.name == name {
			return spec
		}
	}
	t.Fatalf("no hook spec %s", name)
	return hookSpec{}
}

