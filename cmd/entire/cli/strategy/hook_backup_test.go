				t.Helper()
				if err := os.Remove(log); err != nil && !errors.Is(err, os.ErrNotExist) {
					t.Fatal(err)
				}
				ctx, cancel := context.WithTimeout(t.Context(), hookRunTimeout)
				defer cancel()
